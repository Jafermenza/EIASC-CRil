import 'dotenv/config';
import { mkdir, writeFile } from 'node:fs/promises';

const SOURCE = 'Jafermenza/ethiopia-administrative-divisions';
const SOURCE_COMMIT = process.env.GEOGRAPHY_SOURCE_VERSION ?? '418739e33760bf79661f3914e2d8c9cf33248437';
const SOURCE_URL = process.env.GEOGRAPHY_SOURCE_URL ??
  `https://raw.githubusercontent.com/Jafermenza/ethiopia-administrative-divisions/${SOURCE_COMMIT}/data/hierarchy.json`;
const EXPECTED = { regions: 15, zones: 107, woredas: 1148 };
const OUTPUT_DIR = 'data/geography';
const CSV_PATH = `${OUTPUT_DIR}/ethiopia-administrative-divisions.csv`;
const SQL_PATH = `${OUTPUT_DIR}/ethiopia-administrative-divisions.sql`;

const text = (value) => String(value ?? '').trim();
const nameOf = (name, fallback) => text(name?.en) || text(name?.local) || fallback;
const sql = (value) => `'${text(value).replaceAll("'", "''")}'`;
const csv = (value) => {
  const v = text(value);
  return /[",\n\r]/.test(v) ? `"${v.replaceAll('"', '""')}"` : v;
};
const uuidExpr = (prefix, codeExpr) => `md5(${sql(prefix)} || ${codeExpr})::uuid`;

const response = await fetch(SOURCE_URL, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`Geography source returned HTTP ${response.status}`);
const payload = await response.json();
const regions = Array.isArray(payload.data) ? payload.data : [];
if (!regions.length) throw new Error('Geography source does not contain a non-empty data array');

const rows = [];
const regionCodes = new Set();
const zoneCodes = new Set();
const districtCodes = new Set();
for (const region of regions) {
  const regionCode = text(region.id);
  if (!regionCode || !nameOf(region.name, regionCode)) throw new Error('Invalid region in source');
  if (regionCodes.has(regionCode)) throw new Error(`Duplicate region: ${regionCode}`);
  regionCodes.add(regionCode);
  for (const zone of region.zone ?? []) {
    const zoneCode = text(zone.id);
    if (!zoneCode || !nameOf(zone.name, zoneCode)) throw new Error(`Invalid zone under ${regionCode}`);
    if (zoneCodes.has(zoneCode)) throw new Error(`Duplicate zone: ${zoneCode}`);
    zoneCodes.add(zoneCode);
    for (const woreda of zone.woreda ?? []) {
      const districtCode = text(woreda.id);
      const districtName = nameOf(woreda.name, districtCode);
      if (!districtCode || !districtName) throw new Error(`Invalid woreda under ${zoneCode}`);
      if (districtCodes.has(districtCode)) throw new Error(`Duplicate woreda: ${districtCode}`);
      districtCodes.add(districtCode);
      const lower = districtName.toLowerCase();
      const placeType = /sub city|sub-city/.test(lower) ? 'SUBCITY_LABELLED_IN_SOURCE' : /town/.test(lower) ? 'TOWN_LABELLED_IN_SOURCE' : 'DISTRICT_WOREDA';
      rows.push({ regionCode, regionName: nameOf(region.name, regionCode), zoneCode, zoneName: nameOf(zone.name, zoneCode), districtCode, districtName, placeType });
    }
  }
}
if (regionCodes.size !== EXPECTED.regions || zoneCodes.size !== EXPECTED.zones || districtCodes.size !== EXPECTED.woredas) {
  throw new Error(`Source count mismatch: expected ${EXPECTED.regions}/${EXPECTED.zones}/${EXPECTED.woredas}, received ${regionCodes.size}/${zoneCodes.size}/${districtCodes.size}`);
}

await mkdir(OUTPUT_DIR, { recursive: true });
const header = ['region_code','region_name','zone_code','zone_city_name','district_woreda_code','district_woreda_name','source_place_type'];
const csvLines = [header.join(',')];
for (const row of rows) csvLines.push([row.regionCode,row.regionName,row.zoneCode,row.zoneName,row.districtCode,row.districtName,row.placeType].map(csv).join(','));
const attribution = `Data from Open Admin Data (CC-BY-4.0). Source: ${SOURCE}; commit: ${SOURCE_COMMIT}; URL: ${SOURCE_URL}`;
await writeFile(CSV_PATH, `# ${attribution}\n${csvLines.join('\n')}\n`, 'utf8');

const regionRows = [...new Map(rows.map(r => [r.regionCode, r])).values()];
const zoneRows = [...new Map(rows.map(r => [r.zoneCode, r])).values()];
const sqlLines = [
  `-- ${attribution}`,
  '-- Generated by scripts/export-geography.mjs',
  'BEGIN;',
  '',
  '-- Stable UUIDs are derived from source codes so exports are repeatable.',
  'INSERT INTO "Region" ("id","code","name","createdAt","updatedAt") VALUES',
  regionRows.map((r,i) => `(${uuidExpr('region:', sql(r.regionCode))}, ${sql(r.regionCode)}, ${sql(r.regionName)}, NOW(), NOW())${i === regionRows.length-1 ? '' : ','}`).join('\n'),
  'ON CONFLICT ("code") DO UPDATE SET "name" = EXCLUDED."name", "updatedAt" = NOW();',
  '',
  'INSERT INTO "ZoneCity" ("id","code","name","regionId","createdAt","updatedAt") VALUES',
  zoneRows.map((r,i) => `(${uuidExpr('zone:', sql(r.zoneCode))}, ${sql(r.zoneCode)}, ${sql(r.zoneName)}, ${uuidExpr('region:', sql(r.regionCode))}, NOW(), NOW())${i === zoneRows.length-1 ? '' : ','}`).join('\n'),
  'ON CONFLICT ("code") DO UPDATE SET "name" = EXCLUDED."name", "regionId" = EXCLUDED."regionId", "updatedAt" = NOW();',
  '',
  'INSERT INTO "District" ("id","code","name","zoneId","subcityId","createdAt","updatedAt") VALUES',
  rows.map((r,i) => `(${uuidExpr('district:', sql(r.districtCode))}, ${sql(r.districtCode)}, ${sql(r.districtName)}, ${uuidExpr('zone:', sql(r.zoneCode))}, NULL, NOW(), NOW())${i === rows.length-1 ? '' : ','}`).join('\n'),
  'ON CONFLICT ("code") DO UPDATE SET "name" = EXCLUDED."name", "zoneId" = EXCLUDED."zoneId", "subcityId" = NULL, "updatedAt" = NOW();',
  '',
  'COMMIT;',
  ''
];
await writeFile(SQL_PATH, `${sqlLines.join('\n')}`, 'utf8');

console.log(JSON.stringify({ status: 'SUCCESS', source: SOURCE, sourceCommit: SOURCE_COMMIT, regions: regionCodes.size, zones: zoneCodes.size, woredas: districtCodes.size, csv: CSV_PATH, sql: SQL_PATH }, null, 2));
